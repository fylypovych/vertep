"""Transactional module lifecycle with data, journal, rollback and archive.

install -> activate -> deactivate -> update/rollback -> uninstall for one
module. Layout under ``root``::

    state/<module>.json       current record (package, version, state, previous)
    journal/<module>.json     in-flight operation: op, phase, snapshot
    snapshots/<module>/<op>/  pre-change DB export + config + files + record
    data/<module>/config      module configuration (explicit ownership)
    data/<module>/files       module persistent files
    archives/                 admin-only (0700) uninstall archives (0600 tar)

Every change writes the journal *before* touching data. A failure, or a
restart that finds an unfinished journal (``recover``), restores the snapshot
(DB + config + files + record). A module is ACTIVE only after its self-test
passes; there is no READY without it. Archives are never deleted by Vertep.
"""

from __future__ import annotations

import hashlib
import io
import json
import os
import re
import shutil
import tarfile
import threading
import time
import uuid
from pathlib import Path
from typing import Callable

from .manifest import ModuleManifest
from .registry import ModuleRegistry

ARCHIVE_FORMAT = "vertep-module-archive/1"
JOURNAL_FORMAT = "vertep-module-journal/1"
INSTALLED, ACTIVE, INACTIVE, FAILED, UNINSTALLED = "INSTALLED", "ACTIVE", "INACTIVE", "FAILED", "UNINSTALLED"
# Execution modules shipped inside the signed Vertep release (#497): their code
# and manifest come with the release itself, so no separate package signature.
BUNDLED = ("text", "image", "audio", "publisher", "backup", "characters", "brands", "storyboard", "publishing", "monitoring", "web-ui")


MODULE_IMAGES = Path(__file__).resolve().parents[2] / "config" / "module-images.json"


def release_module_images() -> dict[str, str]:
    """Module images the release built before CORE (owner decision 19.11.2026).

    ``config/module-images.json`` is generated by the release workflow and baked
    into the CORE image: ``{name: "ghcr.io/...@sha256:<digest>"}``. A source
    checkout has none; its manifests keep their declared image.
    """
    try:
        data = json.loads(MODULE_IMAGES.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    if not isinstance(data, dict):
        return {}
    import re
    pinned = re.compile(r"[a-z0-9][a-z0-9._/:-]*@sha256:[0-9a-f]{64}")
    return {str(k): v for k, v in data.items() if isinstance(v, str) and pinned.fullmatch(v)}


def bundled_manifest(name: str) -> dict:
    import yaml
    if name not in BUNDLED:
        raise LifecycleError(f"Unknown bundled module: {name}")
    path = Path(__file__).resolve().parents[2] / "modules" / name / "manifest.yaml"
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    if "module" in data:
        data = data["module"]
    else:
        data = data.get("manifest", data)
    image = release_module_images().get(name)
    if image:
        data = {**data, "container": {**(data.get("container") or {"port": 8080}), "image": image}}
    return data


class LifecycleError(RuntimeError):
    pass


def _write_json(path: Path, data: dict, mode: int = 0o600) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    temporary.write_text(json.dumps(data, ensure_ascii=False, sort_keys=True), encoding="utf-8")
    os.chmod(temporary, mode)
    temporary.replace(path)
    # Durable before the next phase begins.
    descriptor = os.open(path.parent, os.O_RDONLY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def migration_sources(package: dict, manifest: ModuleManifest) -> dict[str, str]:
    import base64
    sources = {}
    for migration in manifest.migrations:
        name = f"migrations/{migration['id']}.sql"
        if name not in package["files"]:
            raise LifecycleError(f"Signed package lacks migration {name}")
        sources[migration["id"]] = base64.b64decode(package["files"][name]).decode("utf-8")
    return sources


class ModuleLifecycle:
    def __init__(self, root: Path, verify: Callable[[dict], ModuleManifest], *, database=None, registry=None,
                 self_test: Callable[[ModuleManifest], bool] = lambda manifest: True,
                 active_tasks: Callable[[str], list] = lambda module_id: [],
                 cancel_tasks: Callable[[str], None] = lambda module_id: None,
                 store_credentials: Callable[[str, dict], None] = lambda module_id, credentials: None,
                 system_versions: dict | None = None, drain_timeout: float = 30.0,
                 fault: Callable[[str], None] = lambda point: None,
                 notify: Callable[[str, dict], None] = lambda message, details: None) -> None:
        self.root = Path(root)
        self.verify = verify
        self.database = database
        self.registry = registry
        self.self_test = self_test
        self.active_tasks = active_tasks
        self.cancel_tasks = cancel_tasks
        self.store_credentials = store_credentials
        self.system_versions = system_versions or {}
        self.drain_timeout = drain_timeout
        self.fault = fault  # test hook: raises/exits at a named point
        self.notify = notify  # administrator notification (#513)
        self._locks: dict[str, threading.RLock] = {}
        self._guard = threading.Lock()
        archives = self.root / "archives"
        archives.mkdir(parents=True, exist_ok=True)
        os.chmod(archives, 0o700)
        for record in self.records().values():
            self._publish(record)
        if self.registry is not None:
            for path in sorted(self._tombstones().glob("*.json")):
                # Instances of an uninstalled module stay withheld after a restart.
                if not self._state_path(path.stem).exists():
                    self.registry.set_lifecycle_state(path.stem, UNINSTALLED)

    # -- records -------------------------------------------------------------------
    def _lock(self, module_id: str) -> threading.RLock:
        with self._guard:
            return self._locks.setdefault(module_id, threading.RLock())

    def _state_path(self, module_id: str) -> Path:
        return self.root / "state" / f"{module_id}.json"

    def _journal_path(self, module_id: str) -> Path:
        return self.root / "journal" / f"{module_id}.json"

    def _tombstones(self) -> Path:
        return self.root / "uninstalled"

    def _clear_tombstone(self, module_id: str) -> None:
        (self._tombstones() / f"{module_id}.json").unlink(missing_ok=True)

    def _check_storage(self, module_id: str) -> None:
        """Reject a module ID whose schema/role would coincide with an installed module's."""
        from .data import storage_conflict
        for other in self.records():
            if storage_conflict(module_id, other):
                raise LifecycleError(f"Module ID {module_id} conflicts with installed module {other} (database schema/role)")

    def data_dir(self, module_id: str) -> Path:
        return self.root / "data" / module_id

    def record(self, module_id: str) -> dict | None:
        path = self._state_path(module_id)
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    def records(self) -> dict[str, dict]:
        folder = self.root / "state"
        return {path.stem: json.loads(path.read_text(encoding="utf-8")) for path in sorted(folder.glob("*.json"))} if folder.exists() else {}

    def _save(self, record: dict) -> None:
        _write_json(self._state_path(record["module_id"]), record)
        self._publish(record)

    def _publish(self, record: dict) -> None:
        """Dispatch/API/UI follow the lifecycle: only ACTIVE instances may be READY."""
        if self.registry is not None:
            self.registry.set_lifecycle_state(record["module_id"], record["state"], self._manifest(record))

    def _self_test_failure(self, message: str) -> str:
        reason = getattr(self.self_test, "reason", "")
        return f"{message}: {reason}" if reason else message

    def _manifest(self, record: dict) -> ModuleManifest:
        return ModuleManifest.from_dict(record["package"]["manifest"])

    def _journal(self, module_id: str, **entry) -> None:
        _write_json(self._journal_path(module_id), {"format": JOURNAL_FORMAT, "module_id": module_id, **entry})

    # -- dependency guards -------------------------------------------------------------
    def _active_registry(self, exclude: str | None = None, extra: ModuleManifest | None = None) -> ModuleRegistry:
        registry = ModuleRegistry(self.system_versions)
        pending = {m.module_id: m for m in (self._manifest(r) for r in self.records().values()
                                             if r["state"] == ACTIVE and r["module_id"] != exclude)}
        if extra is not None:
            pending[extra.module_id] = extra
        while pending:
            loaded = [key for key, manifest in pending.items() if registry.register_module(manifest, force=True)]
            if not loaded:
                raise LifecycleError("Module dependencies, interfaces or CORE compatibility are not satisfied")
            for key in loaded:
                pending.pop(key)
        return registry

    def _dependents(self, module_id: str) -> list[str]:
        result = []
        record = self.record(module_id)
        provided = {(p["type"], p["name"]) for p in self._manifest(record).provides} if record else set()
        for other in self.records().values():
            if other["module_id"] == module_id or other["state"] != ACTIVE:
                continue
            manifest = self._manifest(other)
            names = {d["name"] if isinstance(d, dict) else d for d in manifest.dependencies}
            if module_id in names or any((r["type"], r["name"]) in provided for r in manifest.requires):
                result.append(other["module_id"])
        return sorted(result)

    # -- snapshots ----------------------------------------------------------------------
    def _snapshot(self, module_id: str, operation: str) -> Path:
        folder = self.root / "snapshots" / module_id / operation
        if folder.exists():
            shutil.rmtree(folder)
        folder.mkdir(parents=True)
        record = self.record(module_id)
        exported = None
        if self.database is not None and self.database.exists(module_id):
            exported = self.database.export(module_id)
        _write_json(folder / "snapshot.json", {"record": record, "database": exported, "operation": operation,
                                               "version": record["version"] if record else None,
                                               "created_at": time.time()})
        source = self.data_dir(module_id)
        if source.exists():
            shutil.copytree(source, folder / "data", symlinks=True)
        # Bound to the operation and version, and verifiable before it is ever used (#513).
        _write_json(folder / "checksum.json", {"snapshot": _sha256((folder / "snapshot.json").read_bytes()),
                                               "files": self._tree_digest(folder / "data")})
        self._verify_snapshot(folder)
        return folder

    @staticmethod
    def _tree_digest(folder: Path) -> str:
        digest = hashlib.sha256()
        for path in sorted(folder.rglob("*")) if folder.exists() else []:
            if path.is_file() and not path.is_symlink():
                digest.update(path.relative_to(folder).as_posix().encode() + b"\0" + path.read_bytes())
        return digest.hexdigest()

    def _verify_snapshot(self, folder: Path) -> dict:
        try:
            checksum = json.loads((folder / "checksum.json").read_text(encoding="utf-8"))
            raw = (folder / "snapshot.json").read_bytes()
        except (OSError, ValueError) as error:
            raise LifecycleError("Snapshot is incomplete") from error
        if _sha256(raw) != checksum["snapshot"] or self._tree_digest(folder / "data") != checksum["files"]:
            raise LifecycleError("Snapshot does not match its checksum")
        return json.loads(raw)

    def _restore_snapshot(self, module_id: str, folder: Path) -> dict | None:
        snapshot = (self._verify_snapshot(folder) if (folder / "checksum.json").exists()
                    else json.loads((folder / "snapshot.json").read_text(encoding="utf-8")))
        record = snapshot["record"]
        if self.database is not None:
            if snapshot["database"] is not None:
                sources = migration_sources(record["package"], self._manifest(record))
                self.database.restore(module_id, snapshot["database"], sources)
            elif self.database.exists(module_id):
                self.database.drop(module_id)
        target = self.data_dir(module_id)
        if target.exists():
            shutil.rmtree(target)
        if (folder / "data").exists():
            shutil.copytree(folder / "data", target, symlinks=True)
        return record

    # -- operations ---------------------------------------------------------------------
    def _verify(self, package: dict) -> ModuleManifest:
        if "bundled" in package:
            # Always the manifest of the running release, never a supplied copy.
            return ModuleManifest.from_dict(bundled_manifest(package["bundled"]))
        return self.verify(package)  # signature, trust, provenance, UI digests

    def install_bundled(self, name: str) -> dict:
        import base64
        module_dir = Path(__file__).resolve().parents[2] / "modules" / name
        files = {}
        migrations_dir = module_dir / "migrations"
        if migrations_dir.is_dir():
            for migration_file in migrations_dir.glob("*.sql"):
                rel_path = f"migrations/{migration_file.name}"
                files[rel_path] = base64.b64encode(migration_file.read_bytes()).decode("ascii")
        return self.install({"bundled": name, "manifest": bundled_manifest(name), "files": files})

    def install(self, package: dict) -> dict:
        manifest = self._verify(package)
        if "bundled" in package:
            bundled_name = package["bundled"]
            files = package.get("files", {})
            package = {"bundled": bundled_name, "manifest": bundled_manifest(bundled_name), "files": files}
        with self._lock(manifest.module_id):
            if self.record(manifest.module_id):
                raise LifecycleError("Module is already installed; use update")
            self._check_storage(manifest.module_id)
            migration_sources(package, manifest)
            self._active_registry(extra=manifest)  # dependencies + CORE compatibility before any change
            record = {"module_id": manifest.module_id, "version": manifest.version, "state": INSTALLED,
                      "package": package, "previous": None}
            self._save(record)
            self._clear_tombstone(manifest.module_id)
            return {"module_id": manifest.module_id, "state": INSTALLED}

    def _prepare_data(self, record: dict) -> None:
        manifest = self._manifest(record)
        for folder in ("config", "files"):
            (self.data_dir(manifest.module_id) / folder).mkdir(parents=True, exist_ok=True)
        needs_database = manifest.migrations and manifest.placement["target"] != "isolated_lab"
        if manifest.migrations and manifest.placement["target"] == "isolated_lab":
            raise LifecycleError("LAB state uses its own storage (#491); no production database schema")
        if needs_database and self.database is None:
            raise LifecycleError("Module database is not configured")
        if needs_database:
            credentials = self.database.ensure(manifest.module_id)
            if credentials.get("password"):
                self.store_credentials(manifest.module_id, credentials)
            self.fault("before_migrations")
            self.database.migrate(manifest.module_id, manifest.migrations, migration_sources(record["package"], manifest))
            self.fault("after_migrations")

    def activate(self, module_id: str) -> dict:
        with self._lock(module_id):
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            if record["state"] == ACTIVE:
                return {"module_id": module_id, "state": ACTIVE}
            if record.get("blocked"):
                # #511: a confirmed critical threat blocks the module until a fixed version
                # is installed or the administrator lifts the block.
                raise LifecycleError(f"Module is blocked: {record['blocked'].get('reason')}")
            manifest = self._manifest(record)
            self._active_registry(exclude=module_id, extra=manifest)
            if self.registry is not None:
                approved = set(self.registry.placement.approvals.get(module_id, []))
                if not set(manifest.permissions) <= approved:
                    raise LifecycleError("Module permissions are not approved by the administrator")
            operation = uuid.uuid4().hex
            snapshot = self._snapshot(module_id, operation)
            self._journal(module_id, op="activate", phase="snapshot_taken", snapshot=str(snapshot), at=time.time())
            try:
                self._prepare_data(record)
                self._journal(module_id, op="activate", phase="applied", snapshot=str(snapshot), at=time.time())
                if not self.self_test(manifest):
                    raise LifecycleError(self._self_test_failure("Module self-test failed"))
                record["state"] = ACTIVE
                self._save(record)
            except BaseException:
                # The refused activation changed nothing but data prepared for it: no second check.
                self._rollback_to(module_id, snapshot, check=False)
                self._journal_path(module_id).unlink(missing_ok=True)  # undone: nothing left to recover
                raise
            self._journal_path(module_id).unlink()
            return {"module_id": module_id, "state": ACTIVE}

    def block(self, module_id: str, reason: str) -> dict:
        """Protective block (#511): stop the module now; activation is refused until lifted."""
        with self._lock(module_id):
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            record["blocked"] = {"reason": str(reason), "at": time.time()}
            self._save(record)
            self._drain(record)
            return {"module_id": module_id, "state": record["state"], "blocked": record["blocked"]}

    def unblock(self, module_id: str, *, reason: str) -> dict:
        with self._lock(module_id):
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            previous = record.pop("blocked", None)
            self._save(record)
            return {"module_id": module_id, "state": record["state"], "unblocked": bool(previous), "reason": reason}

    def deactivate(self, module_id: str, *, force: bool = False) -> dict:
        with self._lock(module_id):
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            dependents = self._dependents(module_id)
            if dependents and not force:
                raise LifecycleError(f"Active modules depend on it: {', '.join(dependents)}")
            self._drain(record)
            return {"module_id": module_id, "state": record["state"]}

    def _drain(self, record: dict) -> None:
        """Stop new dispatch first, then let active tasks finish or cancel them."""
        if record["state"] == ACTIVE:
            record["state"] = INACTIVE
            self._save(record)
        deadline = time.monotonic() + self.drain_timeout
        while self.active_tasks(record["module_id"]) and time.monotonic() < deadline:
            time.sleep(0.1)
        if self.active_tasks(record["module_id"]):
            self.cancel_tasks(record["module_id"])

    def _result_path(self, operation: str) -> Path:
        return self.root / "results" / f"{operation}.json"

    def _lock_writes(self, module_id: str) -> None:
        if self.database is not None and self.database.exists(module_id):
            self.database.lock_writes(module_id)

    def _unlock_writes(self, module_id: str) -> None:
        if self.database is not None and self.database.exists(module_id):
            self.database.unlock_writes(module_id)

    def moves_into_container(self, record: dict, manifest: ModuleManifest) -> bool:
        """A bundled role module moving into its own container package of the same component
        version (#511): the Vertep release ships the role and the package with one version."""
        return ("bundled" in (record.get("package") or {}) and self._manifest(record).kind == "execution"
                and manifest.kind == "application")

    def update(self, package: dict, *, confirmed: bool, operation_id: str | None = None, _retry: int = 0) -> dict:
        """Approved update; a repeated delivery of the same operation returns its stored result (#513)."""
        if confirmed is not True:
            raise LifecycleError("Update requires explicit administrator confirmation")
        if "bundled" in package:
            raise LifecycleError("Bundled modules are updated with the Vertep release")
        operation = operation_id or uuid.uuid4().hex
        if not re.fullmatch(r"[A-Za-z0-9_-]{1,80}", operation):
            raise LifecycleError("Invalid operation id")
        stored = self._result_path(operation)
        if stored.exists():
            return json.loads(stored.read_text(encoding="utf-8"))
        manifest = self.verify(package)
        module_id = manifest.module_id
        with self._lock(module_id):
            if stored.exists():
                return json.loads(stored.read_text(encoding="utf-8"))
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            if record["version"] == manifest.version and not self.moves_into_container(record, manifest):
                raise LifecycleError("Module version is already installed")
            migration_sources(package, manifest)
            was_active = record["state"] == ACTIVE
            # New version must satisfy its own dependencies and every active dependent.
            self._active_registry(exclude=module_id, extra=manifest)
            if self.registry is not None and not set(manifest.permissions) <= set(self.registry.placement.approvals.get(module_id, [])):
                raise LifecycleError("Expanded permissions need administrator approval before update")
            self._drain(record)
            self._lock_writes(module_id)  # after drain: no writes while snapshot and migrations run
            snapshot = self._snapshot(module_id, operation)
            journal = dict(op="update", phase="snapshot_taken", snapshot=str(snapshot), operation=operation,
                           from_version=record["version"], to_version=manifest.version, was_active=was_active,
                           package=package, retries=_retry, at=time.time())
            self._journal(module_id, **journal)
            previous = {key: record[key] for key in ("version", "package")}
            try:
                updated = {"module_id": module_id, "version": manifest.version, "state": INACTIVE,
                           "package": package, "previous": {**previous, "snapshot": str(snapshot)},
                           "operation": operation}
                if record.get("blocked"):
                    updated["blocked"] = record["blocked"]  # lifted only explicitly (#511)
                self._save(updated)
                self.fault("after_record")
                self._prepare_data(updated)  # local settings in data/config are kept as they are
                self._journal(module_id, **{**journal, "phase": "applied"})
                self.fault("after_apply")
                if not self.self_test(manifest):
                    raise LifecycleError(self._self_test_failure("Updated module self-test failed"))
                updated["state"] = ACTIVE if was_active else INACTIVE
                self._save(updated)
            except BaseException:
                self._rollback_to(module_id, snapshot, reactivate=was_active)
                # Writes open only when the restored previous version is verified (audit #513):
                # a restored module that fails its own check keeps the fence for the administrator.
                self._unlock_if_verified(module_id, previous["version"], operation)
                self._journal_path(module_id).unlink(missing_ok=True)  # undone: nothing left to recover
                raise
            self._unlock_writes(module_id)  # final state verified: writes open again
            self._journal_path(module_id).unlink()
            result = {"module_id": module_id, "state": updated["state"], "version": manifest.version,
                      "operation": operation}
            _write_json(stored, result)
            self.prune(module_id)
            return result

    def rollback(self, module_id: str) -> dict:
        """Return to the version before the last update, with its data snapshot."""
        with self._lock(module_id):
            record = self.record(module_id)
            if not record or not record.get("previous"):
                raise LifecycleError("No previous version to roll back to")
            was_active = record["state"] == ACTIVE
            self._drain(record)
            self._journal(module_id, op="rollback", phase="snapshot_taken", snapshot=record["previous"]["snapshot"], at=time.time())
            self._rollback_to(module_id, Path(record["previous"]["snapshot"]), reactivate=was_active)
            self._journal_path(module_id).unlink(missing_ok=True)
            return {"module_id": module_id, "state": self.record(module_id)["state"], "version": self.record(module_id)["version"]}

    def _rollback_to(self, module_id: str, snapshot: Path, reactivate: bool = False, check: bool = True) -> None:
        record = self._restore_snapshot(module_id, snapshot)
        if record is None:
            self._state_path(module_id).unlink(missing_ok=True)
            if self.registry is not None:
                self.registry.set_lifecycle_state(module_id, None)
            return
        state = record["state"]
        if check and (reactivate or state in (ACTIVE, INACTIVE)):
            # Publish the restored version first (inactive) so nodes converge to it, then require its
            # own self-test, also for an inactive module: the write fence opens only after it (#513).
            # A never activated (INSTALLED) module has nothing running to check.
            self._save({**record, "state": INACTIVE})
            if not self.self_test(self._manifest(record)):
                state = FAILED
            elif reactivate or state == ACTIVE:
                state = ACTIVE
        self._save({**record, "state": state})

    def recover(self) -> list[dict]:
        """After a restart: finish or undo every unfinished operation."""
        results = []
        folder = self.root / "journal"
        for path in sorted(folder.glob("*.json")) if folder.exists() else []:
            journal = json.loads(path.read_text(encoding="utf-8"))
            module_id = journal["module_id"]
            with self._lock(module_id):
                if journal["op"] == "uninstall":
                    if journal["phase"] == "archive_verified":
                        self._remove_data(module_id)
                        outcome = "uninstall_completed"
                    else:
                        record = self.record(module_id)
                        if record:
                            self._save({**record, "state": INACTIVE})
                        outcome = "uninstall_aborted"
                elif journal["op"] == "update" and journal.get("package") is not None:
                    outcome = self._recover_update(module_id, journal, path)
                else:
                    self._rollback_to(module_id, Path(journal["snapshot"]), reactivate=bool(journal.get("was_active")))
                    outcome = "rolled_back"
                path.unlink(missing_ok=True)
                results.append({"module_id": module_id, "op": journal["op"], "outcome": outcome})
        return results

    def _recover_update(self, module_id: str, journal: dict, path: Path) -> str:
        """Unknown state after an interruption (#513): restore the verified snapshot, verify the
        previous version, then make exactly one automatic retry of the approved update."""
        try:
            self._rollback_to(module_id, Path(journal["snapshot"]), reactivate=bool(journal.get("was_active")))
            record = self.record(module_id)
            if record is None or record.get("state") == FAILED or not self.self_test(self._manifest(record)):
                raise LifecycleError("previous version did not pass its check after restore")
        except Exception as error:  # noqa: BLE001 - writes stay locked, nothing runs automatically
            self.notify("Module update stopped: restore was not verified",
                        {"module_id": module_id, "operation": journal.get("operation"), "error": str(error)})
            record = self.record(module_id)
            if record is not None:
                self._save({**record, "attention": {"operation": journal.get("operation"), "error": str(error)}})
            return "restore_failed"
        if int(journal.get("retries", 0)) >= 1:
            # The retry was already spent (also when it was interrupted): the previous version is
            # the verified final state, so writes open and nothing runs again.
            self._unlock_writes(module_id)
            self.notify("Module update failed after its automatic retry",
                        {"module_id": module_id, "operation": journal.get("operation")})
            return "retry_failed"
        # Persist the intent and the spent retry BEFORE retrying (#513): an interruption between
        # restore and retry must not grant a second retry, and writes stay locked meanwhile.
        _write_json(path, {**journal, "phase": "retry_pending", "retries": 1, "at": time.time()})
        self.fault("before_retry")
        try:
            self.update(journal["package"], confirmed=True, operation_id=journal.get("operation"), _retry=1)
        except Exception as error:  # noqa: BLE001 - the one retry failed: stop and tell the administrator
            # Open writes only for a verified previous version; the exception may come from the
            # restore itself, or the restored version may have failed its check (audit #513).
            record = self.record(module_id) or {}
            if (record.get("attention") or {}).get("operation") != journal.get("operation"):
                # (update() itself already kept the fence and reported an unverified restore)
                self._unlock_if_verified(module_id, journal.get("from_version"), journal.get("operation"))
            self.notify("Module update failed after its automatic retry",
                        {"module_id": module_id, "operation": journal.get("operation"), "error": str(error)})
            return "retry_failed"
        return "retried"

    def _unlock_if_verified(self, module_id: str, version: str | None, operation: str | None) -> bool:
        """Lift the write fence only when the module is back on ``version`` and not FAILED;
        otherwise keep it, mark the record for attention and tell the administrator."""
        record = self.record(module_id)
        verified = (record is not None and record.get("state") != FAILED
                    and (version is None or record.get("version") == version))
        if verified:
            self._unlock_writes(module_id)
            return True
        if record is not None:
            self._save({**record, "attention": {"operation": operation,
                                                "error": "restored version is not verified; writes stay locked"}})
        self.notify("Module update stopped: restore was not verified",
                    {"module_id": module_id, "operation": operation})
        return False

    # -- rollback points, retention, purge (#513) ----------------------------------------------
    def rollback_points(self, module_id: str) -> list[dict]:
        """Verified snapshots the administrator may return to, newest first."""
        points = []
        folder = self.root / "snapshots" / module_id
        current = self.record(module_id)
        for path in sorted(folder.iterdir()) if folder.is_dir() else []:
            try:
                snapshot = self._verify_snapshot(path)
            except LifecycleError:
                continue
            record = snapshot.get("record")
            if not record or (current and record.get("version") == current.get("version")):
                continue
            try:
                compatible = self._manifest(record).core_compatible(self.system_versions.get("core_runtime"))
            except Exception:  # noqa: BLE001
                compatible = False
            points.append({"operation": path.name, "version": record["version"],
                           "created_at": snapshot.get("created_at"), "package_available": bool(record.get("package")),
                           "compatible": compatible, "database": snapshot.get("database") is not None})
        newest: dict[str, dict] = {}
        for point in sorted(points, key=lambda item: item.get("created_at") or 0, reverse=True):
            newest.setdefault(point["version"], point)  # one point per version: its latest copy
        return list(newest.values())

    def rollback_to_point(self, module_id: str, operation: str, *, accept_data_loss: bool = False) -> dict:
        """Manual rollback to a suitable point; later database writes are lost only when confirmed."""
        with self._lock(module_id):
            point = next((item for item in self.rollback_points(module_id) if item["operation"] == operation), None)
            if point is None or not point["package_available"] or not point["compatible"]:
                raise LifecycleError("No suitable rollback point")
            if point["database"] and not accept_data_loss:
                stamp = time.strftime("%Y-%m-%d %H:%M:%S UTC", time.gmtime(point["created_at"] or 0))
                raise LifecycleError(f"Restoring the database copy of {stamp} drops later writes; confirm data loss")
            record = self.record(module_id)
            was_active = bool(record and record["state"] == ACTIVE)
            if record:
                self._drain(record)
            self._lock_writes(module_id)
            self._rollback_to(module_id, self.root / "snapshots" / module_id / operation, reactivate=was_active)
            # The fence opens only for a verified restored version (audits #513/#515).
            self._unlock_if_verified(module_id, point["version"], operation)
            restored = self.record(module_id)
            return {"module_id": module_id, "version": restored["version"], "state": restored["state"]}

    def prune(self, module_id: str, keep: int = 3) -> list[str]:
        """Keep snapshots of the active and two previous successful versions; never one an
        unfinished operation or the current record still needs."""
        folder = self.root / "snapshots" / module_id
        if not folder.is_dir():
            return []
        record = self.record(module_id) or {}
        protected = {Path((record.get("previous") or {}).get("snapshot", "")).name}
        journal = self._journal_path(module_id)
        if journal.exists():
            protected.add(Path(json.loads(journal.read_text(encoding="utf-8")).get("snapshot", "")).name)
        entries = []
        for path in folder.iterdir():
            try:
                meta = json.loads((path / "snapshot.json").read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            entries.append((meta.get("created_at") or 0, meta.get("version"), path))
        kept_versions: list[str] = [record.get("version")] if record.get("version") else []
        removed = []
        for _, version, path in sorted(entries, reverse=True):
            if path.name in protected:
                if version not in kept_versions:
                    kept_versions.append(version)  # protected copies count toward the kept versions
                continue
            if version in kept_versions or len(kept_versions) < keep:
                if version not in kept_versions:
                    kept_versions.append(version)
                continue
            shutil.rmtree(path, ignore_errors=True)
            removed.append(path.name)
        return removed

    def purge(self, module_id: str, *, confirmed: bool) -> dict:
        """Full cleanup after uninstall: the archives of the module are deleted (separate action)."""
        if confirmed is not True:
            raise LifecycleError("Purge requires explicit administrator confirmation")
        if self.record(module_id) is not None:
            raise LifecycleError("Uninstall the module first; its archive is the restore point")
        removed = []
        for path in sorted((self.root / "archives").glob("*.tar")):
            try:
                index, _ = self.read_archive(path)
            except (LifecycleError, OSError, ValueError, tarfile.TarError):
                continue
            if index.get("module_id") == module_id:  # never another module with a longer id
                path.unlink()
                removed.append(path.name)
        shutil.rmtree(self.root / "snapshots" / module_id, ignore_errors=True)
        return {"module_id": module_id, "purged": removed}

    # -- uninstall + archive ---------------------------------------------------------------
    def uninstall(self, module_id: str, *, confirmed: bool) -> dict:
        if confirmed is not True:
            raise LifecycleError("Uninstall requires explicit administrator confirmation")
        with self._lock(module_id):
            record = self.record(module_id)
            if record is None:
                raise LifecycleError("Module is not installed")
            dependents = self._dependents(module_id)
            if dependents:
                raise LifecycleError(f"Active modules depend on it: {', '.join(dependents)}")
            self._drain(record)
            self._journal(module_id, op="uninstall", phase="archiving", at=time.time())
            try:
                archive = self.create_archive(module_id)
                self.verify_archive(archive)
            except BaseException as error:
                # Archive failure blocks deletion; the module stays installed and inactive.
                self._journal_path(module_id).unlink(missing_ok=True)
                raise LifecycleError(f"Uninstall blocked: archive failed ({error})") from error
            self._journal(module_id, op="uninstall", phase="archive_verified", archive=str(archive), at=time.time())
            self.fault("after_archive")
            self._remove_data(module_id)
            self._journal_path(module_id).unlink()
            return {"module_id": module_id, "state": UNINSTALLED, "archive": archive.name}

    def _remove_data(self, module_id: str) -> None:
        if self.database is not None and self.database.exists(module_id):
            self.database.drop(module_id)
        shutil.rmtree(self.data_dir(module_id), ignore_errors=True)
        shutil.rmtree(self.root / "snapshots" / module_id, ignore_errors=True)
        # Tombstone before the record goes: instances still reported by nodes get
        # no API/UI/dispatch access, also after a CORE restart.
        _write_json(self._tombstones() / f"{module_id}.json", {"module_id": module_id, "at": time.time()})
        self._state_path(module_id).unlink(missing_ok=True)
        if self.registry is not None:
            self.registry.set_lifecycle_state(module_id, UNINSTALLED)

    def create_archive(self, module_id: str) -> Path:
        """Unencrypted, admin-only tar: DB export, migrations, config, files, signed package."""
        record = self.record(module_id)
        manifest = self._manifest(record)
        members: dict[str, bytes] = {
            "manifest.json": json.dumps(manifest.to_dict(), ensure_ascii=False, sort_keys=True).encode(),
            "package.json": json.dumps(record["package"], ensure_ascii=False, sort_keys=True).encode(),
        }
        if self.database is not None and self.database.exists(module_id):
            members["database.json"] = json.dumps(self.database.export(module_id), ensure_ascii=False, sort_keys=True).encode()
        for migration_id, source in migration_sources(record["package"], manifest).items():
            members[f"migrations/{migration_id}.sql"] = source.encode()
        data = self.data_dir(module_id)
        for kind in ("config", "files"):
            base = data / kind
            for path in sorted(base.rglob("*")) if base.exists() else []:
                if path.is_file() and not path.is_symlink():
                    members[f"{kind}/{path.relative_to(base).as_posix()}"] = path.read_bytes()
        index = {"format": ARCHIVE_FORMAT, "module_id": module_id, "version": record["version"],
                 "created_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "encrypted": False,
                 "checksums": {name: _sha256(content) for name, content in members.items()}}
        target = self.root / "archives" / f"{module_id}-{record['version']}-{time.strftime('%Y%m%dT%H%M%SZ', time.gmtime())}-{uuid.uuid4().hex[:6]}.tar"
        temporary = target.with_suffix(".partial")
        with tarfile.open(temporary, "w") as tar:
            for name, content in {"archive.json": json.dumps(index, sort_keys=True).encode(), **members}.items():
                info = tarfile.TarInfo(name)
                info.size, info.mode, info.mtime = len(content), 0o600, int(time.time())
                tar.addfile(info, io.BytesIO(content))
        os.chmod(temporary, 0o600)
        with open(temporary, "rb") as handle:
            os.fsync(handle.fileno())
        temporary.replace(target)
        return target

    @staticmethod
    def read_archive(path: Path) -> tuple[dict, dict[str, bytes]]:
        members = {}
        with tarfile.open(path, "r") as tar:
            for info in tar.getmembers():
                if not info.isfile() or info.name.startswith("/") or ".." in info.name.split("/"):
                    raise LifecycleError("Unsafe archive member")
                members[info.name] = tar.extractfile(info).read()
        index = json.loads(members.pop("archive.json"))
        if index.get("format") != ARCHIVE_FORMAT:
            raise LifecycleError("Unsupported module archive format")
        if set(members) != set(index["checksums"]) or any(_sha256(members[n]) != d for n, d in index["checksums"].items()):
            raise LifecycleError("Module archive integrity check failed")
        return index, members

    def verify_archive(self, path: Path) -> None:
        """Integrity + a real restore of the DB export into a scratch schema compared with live data."""
        index, members = self.read_archive(path)
        if "database.json" in members and self.database is not None:
            exported = json.loads(members["database.json"])
            sources = {name[len("migrations/"):-4]: content.decode() for name, content in members.items() if name.startswith("migrations/")}
            # Not under the mod_ prefix: no module ID can map onto the scratch schema.
            scratch = f"vtmp_verify_{uuid.uuid4().hex}"
            try:
                self.database.restore(index["module_id"], exported, sources, schema=scratch)
                if self.database.fingerprint(index["module_id"], scratch) != self.database.fingerprint(index["module_id"]):
                    raise LifecycleError("Restored archive data differs from live data")
            finally:
                self.database.drop_schema(scratch, index["module_id"])

    def restore_archive(self, path: Path) -> dict:
        """Reinstall a module from its archive (state INSTALLED until the admin activates)."""
        index, members = self.read_archive(path)
        package = json.loads(members["package.json"])
        manifest = self._verify(package)
        module_id = manifest.module_id
        with self._lock(module_id):
            if self.record(module_id):
                raise LifecycleError("Module is installed; uninstall before restoring an archive")
            self._check_storage(module_id)
            if "database.json" in members and self.database is not None:
                credentials = self.database.ensure(module_id)
                if credentials.get("password"):
                    self.store_credentials(module_id, credentials)
                self.database.restore(module_id, json.loads(members["database.json"]), migration_sources(package, manifest))
            data = self.data_dir(module_id)
            for name, content in members.items():
                kind = name.split("/", 1)[0]
                if kind in ("config", "files"):
                    target = data / name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(content)
            record = {"module_id": module_id, "version": manifest.version, "state": INSTALLED, "package": package, "previous": None}
            self._save(record)
            self._clear_tombstone(module_id)
            return {"module_id": module_id, "state": INSTALLED, "version": manifest.version}

    def archives(self) -> list[dict]:
        result = []
        for path in sorted((self.root / "archives").glob("*.tar")):
            result.append({"name": path.name, "size": path.stat().st_size})
        return result
