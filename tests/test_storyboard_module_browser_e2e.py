"""#501 AC3/AC5/AC6: the Storyboard module reads what the existing CORE flow produced.

A real CORE on a socket serves the production web-v2 bundle to Chromium; the
Storyboard module runs as its own HTTP process-equivalent server and reads
CORE through its module token over HTTP. The storyboard is generated by the
Text Worker and previews by the image Worker through the real task queue; the
revision is requested in the job page of the panel (CORE's own mutation path),
regenerated by the Worker and then read in the module view. Nothing on these
routes is answered by ``page.route``.
"""

import threading
from http.server import ThreadingHTTPServer
from pathlib import Path

from tests import media_harness as harness
from tests.test_media_browser_e2e import (  # noqa: F401  (fixtures)
    _open_job, _script_and_storyboard_ready, browser, core, expect)

MODULE_DIR = Path(__file__).resolve().parents[1] / "modules" / "storyboard"


def _storyboard_module(core, monkeypatch, tmp_path):
    from core.module.gateway import issue_token
    from core.module.instances import ModuleInstanceRegistry, PlacementStore
    from core.module.lifecycle import bundled_manifest
    from core.module.manifest import ModuleManifest
    monkeypatch.syspath_prepend(str(MODULE_DIR))
    import storyboard_module
    monkeypatch.setenv("VERTEP_MODULE_AUDIT_FILE", str(tmp_path / "audit.jsonl"))
    registry = ModuleInstanceRegistry({"core_runtime": "0.0.4.13"}, PlacementStore(tmp_path / "placement.json"))

    # Only the module registry is the test's; job orchestration stays CORE's own.
    monkeypatch.setattr("core.module.gateway._modules_or_none", lambda: registry)
    monkeypatch.setattr(storyboard_module, "CORE", core["url"])
    monkeypatch.setattr(storyboard_module, "TOKEN", issue_token("storyboard", "app-node"))
    from tests.test_scenario_library_508 import make_sqlite_scenario_store
    monkeypatch.setattr(storyboard_module, "_state", {"connection": None, "store": make_sqlite_scenario_store()})
    server = ThreadingHTTPServer(("127.0.0.1", 0), storyboard_module.Handler)
    threading.Thread(target=server.serve_forever, daemon=True).start()
    manifest = ModuleManifest.from_dict(bundled_manifest("storyboard"))
    registry.report_node("app-node", [{**manifest.to_dict(), "ready": True,
                                       "endpoint": f"http://127.0.0.1:{server.server_address[1]}"}])
    registry.set_placement("storyboard", ["app-node"])
    registry.approve_permissions("storyboard", list(manifest.permissions))
    assert registry.ready_instances("storyboard")
    return server


def test_a_revision_made_in_the_job_page_is_read_in_the_storyboard_module(core, browser, monkeypatch,  # noqa: F811
                                                                          tmp_path):
    api, page = core["api"], browser["page"]
    server = _storyboard_module(core, monkeypatch, tmp_path)
    try:
        job_id = _script_and_storyboard_ready(api, core["monkeypatch"], core["character_id"])
        frame = page.frame_locator("[data-testid=module-extension-frame]")

        # The module view shows version 1 as CORE holds it.
        page.goto(f"{browser['url']}/modules/storyboard")
        expect(frame.locator("body")).to_contain_text(job_id)
        expect(frame.locator("body")).to_contain_text("версія 1")

        # The editor asks for a revision on the job page: CORE's own mutation path.
        _open_job(browser, job_id)
        revision = "Переробити композицію кадрів"
        page.once("dialog", lambda dialog: dialog.accept(revision))
        with page.expect_response(lambda response: response.request.method == "POST"
                                  and response.url.endswith("/storyboards/regenerate")) as revised:
            page.get_by_test_id("revision-job-button").click()
        assert revised.value.ok, revised.value.text()
        harness.run_storyboard_task(api, job_id, core["monkeypatch"], expect_revision=revision)
        harness.wait_for_status(api, job_id, "STORYBOARD_PENDING_APPROVAL")
        harness.submit_storyboard_previews(api, job_id, count=2)
        harness.wait_for_status(api, job_id, "STORYBOARD_READY")

        # The module reads the new version, its revision-driven scenes and history.
        page.goto(f"{browser['url']}/modules/storyboard")
        expect(frame.locator("body")).to_contain_text("версія 2")
        expect(frame.locator("body")).to_contain_text("[sb-rev:")
        detail = page.request.get(f"{browser['url']}/api/modules/storyboard/v1/storyboards/{job_id}").json()
        core_boards = api.get(f"/api/jobs/{job_id}/storyboards").json()
        assert [v["version"] for v in detail["storyboards"]] == [b["version"] for b in core_boards] == [1, 2]
        assert [v["status"] for v in detail["storyboards"]] == [b["status"] for b in core_boards]
        assert detail["storyboards"][1]["revision_request"] == revision
        assert [s["prompt"] for s in detail["storyboards"][1]["scenes"]] == \
            [s["prompt"] for s in core_boards[1]["scenes"]]

        # The panel relays only this module's own API for the extension (no network of its own).
        extension = next(f for f in page.frames if "/api/modules/ui/storyboard/" in f.url)
        statuses = extension.evaluate("""async (paths) => {
            const out = [];
            for (const path of paths) {
              const response = await vertepFetch(path);
              out.push(response.status);
            }
            try { await fetch('/api/session'); out.push('network'); } catch (error) { out.push('no-network'); }
            return out;
        }""", ["/api/modules/storyboard/v1/storyboards", "/api/settings/users",
               "/api/modules/storyboard/v1/../../../settings/users", "/api/modules/characters/v1/characters"])
        assert statuses == [200, 403, 403, 403, "no-network"]
        # The blocked direct fetch is the expected CSP refusal, not a page failure.
        browser["console_errors"][:] = [m for m in browser["console_errors"] if "Content Security Policy" not in m]
    finally:
        server.shutdown()
